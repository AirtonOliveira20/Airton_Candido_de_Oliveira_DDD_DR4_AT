package br.com.cinepass.historico.mensageria;

import br.com.cinepass.historico.observability.TraceSupport;
import jakarta.annotation.PostConstruct;
import org.apache.kafka.clients.consumer.ConsumerRecord;
import org.slf4j.*;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.scheduling.annotation.*;
import org.springframework.stereotype.Component;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.TransactionDefinition;
import org.springframework.transaction.support.TransactionTemplate;
import tools.jackson.databind.json.JsonMapper;
import java.util.*;
import java.util.concurrent.*;
import java.nio.charset.StandardCharsets;
import jakarta.annotation.PreDestroy;


@Component
@EnableScheduling
public class ReservaInbox {
    private static final Logger log=LoggerFactory.getLogger(ReservaInbox.class);
    private final JdbcTemplate db;
    private final TransactionTemplate outer, business;
    private final EventoReservaParser parser;
    private final br.com.cinepass.historico.application.HistoricoService service;
    private final TraceSupport traces;
    private final JsonMapper json;
    private final int maxAttempts;
    private final long retryMillis;
    private final ExecutorService workers=Executors.newFixedThreadPool(3);
    private final Set<Long> running=ConcurrentHashMap.newKeySet();
    public ReservaInbox(JdbcTemplate db,PlatformTransactionManager tm,EventoReservaParser parser,
            br.com.cinepass.historico.application.HistoricoService service,TraceSupport traces,JsonMapper json,
            @Value("${cinepass.inbox.max-attempts:4}") int maxAttempts,
            @Value("${cinepass.inbox.retry-ms:1000}") long retryMillis) {
        this.db=db;this.parser=parser;this.service=service;this.traces=traces;this.json=json;
        this.maxAttempts=Math.max(1,maxAttempts);this.retryMillis=Math.max(0,retryMillis);
        outer=new TransactionTemplate(tm); business=new TransactionTemplate(tm);
        business.setPropagationBehavior(TransactionDefinition.PROPAGATION_REQUIRES_NEW);
    }
    @PostConstruct
    public void initialize() {
        db.execute("""
            create table if not exists reserva_inbox (
                id bigint generated by default as identity primary key,
                topic varchar(255) not null, partition_no integer not null, offset_no bigint not null,
                aggregate_key varchar(100) not null, payload text, trace_context text not null,
                status varchar(20) not null default 'PENDING', attempts integer not null default 0,
                next_attempt_at timestamp with time zone not null default current_timestamp,
                last_error varchar(150), received_at timestamp with time zone not null default current_timestamp,
                unique(topic,partition_no,offset_no))
            """);
        db.execute("create index if not exists idx_inbox_key_order on reserva_inbox(aggregate_key,id,status)");
    }
    public void receive(ConsumerRecord<String,String> record) {
        String key=record.key();
        if(key==null || !key.matches("[0-9a-fA-F-]{36}")) {
            key="invalid-"+UUID.nameUUIDFromBytes((record.topic()+":"+record.partition()+":"+record.offset()).getBytes(StandardCharsets.UTF_8));
        }
        String aggregate=key;
        outer.executeWithoutResult(tx->db.update("""
            insert into reserva_inbox(topic,partition_no,offset_no,aggregate_key,payload,trace_context)
            values(?,?,?,?,?,?) on conflict(topic,partition_no,offset_no) do nothing
            """,record.topic(),record.partition(),record.offset(),aggregate,record.value(),json.writeValueAsString(traces.capture())));
        log.atInfo().addKeyValue("reservaId",TraceSupport.safe(aggregate))
            .addKeyValue("correlationId",TraceSupport.safe(traces.capture().get("correlationId")))
            .log("operacao=KAFKA resultado=RECEBIDO particao={} offset={}",record.partition(),record.offset());
    }
    public List<Long> eligible() {
        return db.queryForList("""
            select i.id from reserva_inbox i where i.status='PENDING' and i.next_attempt_at<=current_timestamp
            and not exists(select 1 from reserva_inbox older where older.aggregate_key=i.aggregate_key
                and older.id<i.id and older.status<>'DONE') order by i.id limit 100
            """,Long.class);
    }
    @Scheduled(fixedDelayString="${cinepass.inbox.poll-ms:500}", initialDelay=5000)
    public void poll() {
        try { for(Long id:eligible()) if(running.add(id)) workers.submit(()->{
            try { process(id); }
            catch(Exception ex){log.error("operacao=INBOX resultado=FALHA_INFRA inboxId={} erro={}",id,ex.getClass().getSimpleName());}
            finally {running.remove(id);}
        }); } catch(Exception ex){log.error("operacao=INBOX resultado=FALHA_POLL erro={}",ex.getClass().getSimpleName());}
    }
    public void process(long id) {
        outer.executeWithoutResult(tx->{

            if(!Boolean.TRUE.equals(db.queryForObject("select pg_try_advisory_xact_lock(?)",Boolean.class,-id))) return;
            var rows=db.queryForList("select * from reserva_inbox where id=? and status='PENDING' and next_attempt_at<=current_timestamp",id);
            if(rows.isEmpty()) return;
            var row=rows.getFirst();
            long predecessors=db.queryForObject("select count(*) from reserva_inbox where aggregate_key=? and id<? and status<>'DONE'",Long.class,row.get("aggregate_key"),id);
            if(predecessors>0) return;
            Map<String,String> carrier=json.readValue((String)row.get("trace_context"),new tools.jackson.core.type.TypeReference<Map<String,String>>(){});
            try {
                traces.within(carrier,"inbox.process",()->business.execute(status->{
                    EventoReserva event=parser.ler((String)row.get("payload"));
                    if(!event.reservaId().toString().equalsIgnoreCase((String)row.get("aggregate_key")))
                        throw new IllegalArgumentException("key mismatch");
                    Map<String,String> old=MDC.getCopyOfContextMap();
                    try {
                        MDC.put("reservaId",event.reservaId().toString()); MDC.put("eventId",event.eventId().toString());
                        MDC.put("correlationId",TraceSupport.safe(event.correlationId()));
                        MDC.put("destinatario",event.payload().clienteId().toString());
                        log.info("operacao=EVENTO resultado=INICIO tipo={}",TraceSupport.safe(event.eventType()));
                        Object result=service.processar(event);
                        db.update("update reserva_inbox set status='DONE',last_error=null where id=?",id);
                        log.info("operacao=EVENTO resultado=CONCLUSAO efeito={}",result);
                        return null;
                    } finally {if(old==null) MDC.clear();else MDC.setContextMap(old);}
                }));
            } catch(Exception ex) {
                int attempts=((Number)row.get("attempts")).intValue()+1;
                String status=attempts>=maxAttempts?"DEAD":"PENDING";
                db.update("update reserva_inbox set attempts=?,status=?,last_error=?,next_attempt_at=? where id=?",
                    attempts,status,ex.getClass().getSimpleName(),java.sql.Timestamp.from(java.time.Instant.now().plusMillis(retryMillis)),id);
                log.atError().addKeyValue("reservaId",TraceSupport.safe((String)row.get("aggregate_key")))
                    .addKeyValue("eventId",TraceSupport.safe(carrier.get("eventId")))
                    .addKeyValue("correlationId",TraceSupport.safe(carrier.get("correlationId")))
                    .log("operacao=EVENTO resultado={} inboxId={} tentativa={} erro={}",status,id,attempts,ex.getClass().getSimpleName());
            }
        });
    }
    public List<Map<String,Object>> failures(){return db.queryForList("select id,topic,partition_no,offset_no,aggregate_key,status,attempts,last_error,received_at from reserva_inbox where status='DEAD' order by id limit 100");}
    public List<Map<String,Object>> detail(long id){return db.queryForList("select * from reserva_inbox where id=?",id);}
    public boolean retry(long id){return db.update("update reserva_inbox set status='PENDING',attempts=0,next_attempt_at=current_timestamp where id=? and status='DEAD'",id)==1;}
    @PreDestroy public void close(){workers.shutdown();}
}
